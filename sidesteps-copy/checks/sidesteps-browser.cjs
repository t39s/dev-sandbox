const { chromium, devices } = require('playwright');
const { test } = require('node:test');
const assert = require('node:assert/strict');

test('пользовательские сценарии в мобильном viewport', async (t) => {
  const browser = await chromium.launch({executablePath: process.env.SIDESTEPS_CHROMIUM, headless: true, args: ['--no-sandbox']});
  t.after(() => browser.close());
  const context = await browser.newContext(devices['iPhone 12 Mini'] || {
    ...devices['iPhone 12'], viewport: {width: 375, height: 812}, screen: {width: 375, height: 812}
  });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const base = process.env.SIDESTEPS_TEST_URL || 'http://127.0.0.1:8792/sidesteps-copy/iteration-03/';
  const button = (name) => page.getByRole('button', {name, exact: true});
  const click = (name) => button(name).click();
  const lap = async () => { await page.waitForTimeout(520); await click('Отсечка или стоп'); };
  const visible = (text) => page.getByText(text, {exact: true}).first().waitFor();
  const openExercise = () => page.getByRole('tab', {name: 'Новое упражнение'}).click();
  const startStopForm = async () => {
    await openExercise();
    await page.getByLabel('Попыток в тренировке').selectOption('1');
    await page.getByLabel('Режим измерения').selectOption('stop');
    await click('Начать тренировку');
  };

  await page.goto(base);
  await visible('Пока нет тренировок');
  await visible('Пока нет завершённых тренировок.');
  await visible('Нет предыдущих тренировок');
  await openExercise();
  assert.equal(await page.getByLabel('Попыток в тренировке').inputValue(), '2');
  assert.equal(await page.getByLabel('Режим измерения').inputValue(), 'laps');
  await click('Начать тренировку');
  await visible('Попытка 1 из 2');
  await click('Начать измерение');
  for (let i = 0; i < 19; i++) await lap();
  await visible('19 / 20 интервалов');
  await lap();
  await visible('Отдых');
  await page.reload();
  await visible('Отдых');
  await click('Начать раньше');
  await visible('Попытка 2 из 2');
  await click('Начать измерение');
  for (let i = 0; i < 20; i++) await lap();
  await visible('Тренировка завершена');
  await page.getByText('Подробнее', {exact: true}).click();
  await page.getByText('Время каждого интервала (20)', {exact: true}).first().click();
  await visible('Интервал 20');
  await click('На главную');
  await startStopForm();
  await click('Начать измерение');
  await click('Настройки');
  await click('Выключить');
  await visible('Выключен');
  await click('Назад');
  await visible('КОСНИСЬ ДЛЯ СТОПА');
  await page.reload();
  await visible('КОСНИСЬ ДЛЯ СТАРТА');
  await click('Начать измерение');
  await click('Отсечка или стоп');
  await visible('КОСНИСЬ ДЛЯ СТОПА');
  await lap();
  await visible('Тренировка завершена');
  await visible('★ Новый рекорд!');
  await click('На главную');
  await page.reload();
  await visible('Мой прогресс');
  assert.equal(await page.getByRole('img', {name: /последних 2 завершённых/}).count(), 1);
  await click('Настройки');
  await visible('Выключен');
  const backup = page.waitForEvent('download');
  await click('Сохранить');
  const path = await (await backup).path();
  await page.locator('input[type=file]').setInputFiles(path);
  await visible('Данные загружены.');
  await click('Назад');
  await page.getByRole('link', {name:'Войти'}).click();
  await visible('Вход администратора');
  await click('Назад');
  await visible('Мой прогресс');
  const dimensions = await page.evaluate(() => [innerWidth, document.documentElement.scrollWidth]);
  assert.equal(dimensions[0], 375);
  assert.deepEqual(dimensions, [375, 375]);
  assert.deepEqual(errors, []);
});
